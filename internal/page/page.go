// Package page renders the generated pages of a workspace, checks them
// against what is on disk, and plans what `mason sync` writes. Today there is
// one kind: each initiative's README, which is a read-only snapshot of the
// records, committed so that browsing on GitHub still works. Nothing reads a
// page back except to compare it with the page the records give. See
// docs/context-graph/03-implementation.md section 7.
package page

import (
	"fmt"
	"path"
	"path/filepath"
	"strings"

	"github.com/andycondon/loremason/internal/index"
)

// Marker is the line that says a page was written by mason. It is a whole
// line of its own, so a merge conflict elsewhere in the page leaves it in
// place and the page is still recognised as generated.
const Marker = "<!-- generated by mason; edit the records, then run mason sync -->"

// Path returns the workspace-relative path of the README of the initiative
// with the slug. It is the one home for that layout.
func Path(slug string) string { return "initiatives/" + slug + "/README.md" }

// README renders the page of an initiative. It takes no clock and reads no
// files, so the same overview gives the same bytes. The page's title, the
// links to records and the people are escaped for Markdown; the purpose,
// goals and body are the initiative's own Markdown and are written as they
// are. Empty sections are left out.
func README(o *index.Overview) []byte {
	var b strings.Builder
	dir := path.Dir(Path(o.Slug))
	fmt.Fprintf(&b, "# %s\n\n%s\n\n", escape(o.Initiative.Title), Marker)
	fmt.Fprintf(&b, "*Generated from the initiative record [`%s`](%s). Edit the records, then run `mason sync`.*\n",
		o.Initiative.ID, linkTo(dir, o.Path))
	if p := strings.TrimSpace(o.Purpose); p != "" {
		fmt.Fprintf(&b, "\n%s\n", p)
	}
	if len(o.Goals) > 0 {
		b.WriteString("\n## Goals\n\n")
		for _, g := range o.Goals {
			fmt.Fprintf(&b, "- %s\n", strings.ReplaceAll(strings.TrimSpace(g), "\n", "\n  "))
		}
	}
	if body := strings.TrimSpace(o.Body); body != "" {
		fmt.Fprintf(&b, "\n%s\n", body)
	}
	if len(o.People) > 0 {
		b.WriteString("\n## People\n\n")
		for _, p := range o.People {
			b.WriteString("- " + escape(p.Title))
			if p.Role != "" {
				b.WriteString(", " + escape(p.Role))
			}
			b.WriteString("\n")
		}
	}
	section(&b, "Design docs", dir, o.DesignDocs)
	section(&b, "PRDs", dir, o.PRDs)
	section(&b, "Tasks", dir, o.Tasks)
	return []byte(b.String())
}

// section writes a list of records, each linked by title with its status
// and, for a task, its progress. It writes nothing for an empty list.
func section(b *strings.Builder, heading, dir string, entries []index.Entry) {
	if len(entries) == 0 {
		return
	}
	fmt.Fprintf(b, "\n## %s\n\n", heading)
	for _, e := range entries {
		fmt.Fprintf(b, "- [%s](%s)", escape(e.Title), linkTo(dir, e.Path))
		var notes []string
		if e.Status != "" {
			notes = append(notes, e.Status)
		}
		if e.Progress != "" {
			notes = append(notes, strings.ReplaceAll(e.Progress, "_", " "))
		}
		if len(notes) > 0 {
			b.WriteString(": " + strings.Join(notes, ", "))
		}
		b.WriteString("\n")
	}
}

// linkTo returns the path of a workspace file as a link target relative to
// the folder dir, with the characters that end a Markdown link escaped.
func linkTo(dir, file string) string {
	rel, err := filepath.Rel(filepath.FromSlash(dir), filepath.FromSlash(file))
	if err != nil {
		rel = file
	}
	return strings.NewReplacer(" ", "%20", "(", "%28", ")", "%29").Replace(filepath.ToSlash(rel))
}

// escape makes text safe to use as Markdown link text or a heading.
func escape(s string) string {
	var b strings.Builder
	for _, r := range s {
		if strings.ContainsRune("\\`*_[]<>!|~&", r) {
			b.WriteByte('\\')
		}
		b.WriteRune(r)
	}
	return b.String()
}
